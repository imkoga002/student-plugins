"""Research is tied to the student's questions and logs itself; the machine stage of source verification (the
verifier). Live API tests run only with RK_NET_TESTS=1. The verifier fixtures use real works (Walters & Wilder 2023,
Scientific Reports 13:14045, DOI 10.1038/s41598-023-41032-5; a CiNii Books record and an NDL record seen in live
responses during development)."""
import json
import os
import subprocess
import sys
import time
import unittest

from helpers import PLUGIN, Env

sys.path.insert(0, os.path.join(PLUGIN, "scripts", "rk"))
from rklib import netutil, refcheck, search  # noqa: E402

NET = os.environ.get("RK_NET_TESTS") == "1"
RK = os.path.join(PLUGIN, "scripts", "rk")
QUESTIONS = "# 調査の問い(学生が書く)\n\n| id | 小問い(自分の言葉で) | 何が分かれば答えになるか | 状態 |\n|---|---|---|---|\n| Q1 | 現象 X はいつから見られるか(見本) | 年ごとの件数 | 着手 |\n| Q2 | | | 未着手 |\n"


class Questions(unittest.TestCase):
    def setUp(self):
        self.E = Env()
        self.E.write("research/questions.md", QUESTIONS)

    def tearDown(self):
        self.E.cleanup()

    def test_question_ids_need_a_body(self):
        self.assertEqual(search.question_ids(self.E.proj), {"Q1"})

    def test_unknown_question_stops_before_any_request(self):
        t = time.time()
        r = self.E.rk("search", "crossref", "現象 X", "--question-ref", "Q2", extra={"HTTPS_PROXY": "http://127.0.0.1:9", "HTTP_PROXY": "http://127.0.0.1:9"})
        self.assertEqual(r.returncode, 2)
        self.assertIn("research/questions.md にない", r.stderr)
        self.assertIn("通信はしていない", r.stderr)
        self.assertLess(time.time() - t, 20)
        self.assertEqual(self.E.read("research", "search-log.jsonl").strip(), "")

    def test_search_logs_itself(self):
        snippet = ("import sys,json\nsys.path.insert(0,%r)\nfrom rklib import search, netutil\n"
                   "body=json.dumps({'message':{'total-results':42,'items':[{'DOI':'10.1/x','title':['T'],'issued':{'date-parts':[[2021]]}}]}}).encode()\n"
                   "netutil.Net.get=lambda self,url,accept='application/json':(200,body)\n"
                   "rec,items,extra=search.run(%r,'crossref','現象 X','Q1',purpose='counter')\nprint(json.dumps(rec,ensure_ascii=False))\n" % (RK, self.E.proj))
        r = self.E.run([sys.executable, "-B", "-c", snippet], cwd=self.E.proj)
        self.assertEqual(r.returncode, 0, r.stderr)
        line = json.loads(self.E.read("research", "search-log.jsonl").strip())
        for k, v in (("db", "crossref"), ("query", "現象 X"), ("hits", 42), ("question_ref", "Q1"), ("purpose", "counter"), ("auto", True)):
            self.assertEqual(line[k], v, k)
        self.assertRegex(line["date"], r"^\d{4}-\d{2}-\d{2}$")
        self.assertIn("api.crossref.org", line["endpoint"])

    def test_ndl_is_sequential_across_processes(self):
        lock = os.path.join(self.E.base, "ndl.lock")
        out = os.path.join(self.E.base, "times")
        code = ("import sys,time\nsys.path.insert(0,%r)\nfrom rklib.netutil import Lock\n"
                "with Lock(%r):\n    a=time.time(); time.sleep(1.0); b=time.time()\nopen(%r,'a').write('%%f %%f\\n'%%(a,b))\n" % (RK, lock, out))
        ps = [subprocess.Popen([sys.executable, "-B", "-c", code]) for _ in range(2)]
        for p in ps:
            p.wait(timeout=60)
        (a1, b1), (a2, b2) = sorted(tuple(map(float, l.split())) for l in open(out).read().split("\n") if l.strip())
        self.assertGreaterEqual(a2, b1 - 0.01)

    def test_selected_without_reason_is_an_error(self):
        with open(self.E.path("research", "search-log.jsonl"), "a", encoding="utf-8") as f:
            f.write(json.dumps({"id": "S001", "date": "2026-11-04", "db": "crossref", "query": "現象 X", "filters": "", "hits": 3,
                                "question_ref": "Q1", "purpose": "main", "selected": ["doi:10.1/x"], "reason": "", "by": "agent", "auto": True}) + "\n")
        r = self.E.rk("check")
        self.assertEqual(r.returncode, 1)
        self.assertIn("reason(選んだ理由)が空", r.stdout)

    def test_annotate_requires_known_question(self):
        self.E.rk("searchlog", "add", "--db", "OPAC", "--query", "現象 X", "--question-ref", "Q1", "--by", "human")
        r = self.E.rk("searchlog", "annotate", "S001", "--question-ref", "Q7")
        self.assertNotEqual(r.returncode, 0)
        r = self.E.rk("searchlog", "annotate", "S001", "--selected", "isbn:x", "--reason", "Q1 の年代の手がかり")
        self.assertEqual(r.returncode, 0, r.stderr)


class Verifier(unittest.TestCase):
    WALTERS = {"title": ["Fabrication and errors in the bibliographic citations generated by ChatGPT"],
               "author": [{"family": "Walters", "given": "William H."}, {"family": "Wilder", "given": "Esther Isabelle"}],
               "issued": {"date-parts": [[2023, 9, 7]]}}
    FULL = {"title": "Fabrication and errors in the bibliographic citations generated by ChatGPT", "authors": "Walters, William H.", "year": 2023}

    def test_identity_needs_metadata(self):
        self.assertEqual(refcheck.judge(self.FULL, self.WALTERS)["status"], "IDENTITY_CONFIRMED")
        self.assertEqual(refcheck.judge({"title": "Fabrication"}, self.WALTERS)["status"], "METADATA_MISMATCH")
        self.assertEqual(refcheck.judge({}, self.WALTERS)["status"], "CANDIDATE")

    def test_retraction_both_sides(self):
        retracted = dict(self.WALTERS, **{"updated-by": [{"DOI": "10.1177/17588359211061903", "type": "retraction", "source": "retraction-watch"}]})
        self.assertEqual(refcheck.judge({"year": 2023}, retracted)["status"], "RETRACTED")
        notice = dict(self.WALTERS, **{"update-to": [{"DOI": "10.1177/1758835919874651", "type": "retraction", "source": "retraction-watch"}]})
        self.assertIn("撤回通知", " ".join(refcheck.judge({"title": self.WALTERS["title"][0]}, notice)["notes"]))

    def test_datacite_has_no_retraction_data(self):
        attrs = {"doi": "10.5281/zenodo.1", "titles": [{"title": "A dataset title for testing"}],
                 "creators": [{"nameType": "Personal", "givenName": "Taro", "familyName": "Sample"}], "publicationYear": 2024}
        res = refcheck.judge({"title": "A dataset title for testing", "authors": "Sample, Taro", "year": 2024}, refcheck.datacite_item(attrs), "datacite")
        self.assertEqual(res["status"], "IDENTITY_CONFIRMED")
        self.assertIn("未確認", " ".join(res["notes"]))

    def test_cinii_and_ndl(self):
        data = {"@graph": [{"items": [{"@id": "https://ci.nii.ac.jp/ncid/BB05639624", "title": "議論の技法 : トゥールミンモデルの原点"}]}]}
        self.assertEqual(refcheck.judge_cinii(data, "BB05639624", "ncid", "議論の技法 : トゥールミンモデルの原点")["status"], "IDENTITY_CONFIRMED")
        self.assertEqual(refcheck.judge_cinii(data, "BB00000000", "ncid", "議論の技法")["status"], "CANDIDATE")
        xml = "<searchRetrieveResponse><numberOfRecords>1</numberOfRecords><record>&lt;rdf:Description rdf:about=&quot;https://ndlsearch.ndl.go.jp/books/R100000002-I000008374835&quot;&gt;&lt;dc:title&gt;論理トレーニング&lt;/dc:title&gt;</record></searchRetrieveResponse>"
        self.assertEqual(refcheck.judge_ndl(xml, "R100000002-I000008374835", "論理トレーニング")["status"], "IDENTITY_CONFIRMED")

    def test_network_failure_sets_no_status(self):
        class Dead(object):
            mailto = None

            def get(self, *a, **k):
                raise OSError("network down")

            def get_ndl(self, *a, **k):
                raise OSError("network down")
        res = refcheck.check_ref({"id": "S1", "doi": "10.1038/s41598-023-41032-5", "title": "x"}, Dead())
        self.assertIsNone(res.get("status"))

        class Forbidden(Dead):
            def get(self, *a, **k):
                return 403, b""
        res = refcheck.check_ref({"id": "S1", "doi": "10.1038/s41598-023-41032-5", "title": "x"}, Forbidden())
        self.assertNotIn(res.get("status"), ("IDENTITY_CONFIRMED", "VERIFIED"))

    def test_isbn10_not_validated(self):
        self.assertEqual(refcheck.check_ref({"id": "S1", "isbn": "4782802056"}, None)["reason"], "isbn10_not_validated")
        self.assertTrue(refcheck.isbn13_valid("9784489020940"))
        self.assertFalse(refcheck.isbn13_valid("9784489020941"))

    def test_verifier_never_writes_human_columns(self):
        rows = [{"id": "S1", "machine_status": "", "human_status": ""}]
        with self.assertRaises(ValueError):
            refcheck.apply_results(rows, [{"id": "S1", "status": "VERIFIED", "checked_at": "t"}])
        refcheck.apply_results(rows, [{"id": "S1", "status": "IDENTITY_CONFIRMED", "checked_at": "t"}])
        self.assertEqual(rows[0]["human_status"], "")

    def test_appid_is_redacted(self):
        self.assertEqual(netutil.redact("https://cir.nii.ac.jp/opensearch/all?q=x&appid=SECRET123&count=1"),
                         "https://cir.nii.ac.jp/opensearch/all?q=x&appid=***&count=1")

    @unittest.skipUnless(NET, "set RK_NET_TESTS=1 for live API tests")
    def test_live_identity_mismatch_not_found_and_retraction(self):
        net = refcheck.Net()
        self.assertEqual(refcheck.check_ref(dict(self.FULL, id="a", doi="10.1038/s41598-023-41032-5"), net)["status"], "IDENTITY_CONFIRMED")
        self.assertEqual(refcheck.check_ref({"id": "b", "doi": "10.1038/s41598-023-41032-5", "title": "Fabrication"}, net)["status"], "METADATA_MISMATCH")
        self.assertEqual(refcheck.check_ref({"id": "c", "doi": "10.1038/s41598-099-99999-9", "title": "x"}, net)["status"], "NOT_FOUND")
        self.assertEqual(refcheck.check_ref({"id": "d", "doi": "10.1177/1758835919874651", "year": 2019}, net)["status"], "RETRACTED")


if __name__ == "__main__":
    unittest.main()
