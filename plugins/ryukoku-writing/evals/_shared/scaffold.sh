#!/usr/bin/env bash
# Shared scaffold for the ryukoku-writing evals: an initialised project in the eval workspace ($PWD), so the hooks
# are active, with placeholder content only ("現象 X", "要因 A"; no real topic). Usage: scaffold.sh [ja|en]
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
PLUGIN="${CLAUDE_PLUGIN_ROOT:-$(cd "$HERE/../.." && pwd)}"
LANGC="${1:-ja}"
bash "$PLUGIN/scripts/init-project.sh" --dir "$PWD" --lang "$LANGC" >/dev/null
if [ "$LANGC" = ja ]; then
cat > manuscript/main.md <<'MD'
---
title: "(見本の原稿)"
---

# はじめに

現象 X は近年よく話題になる。本稿は現象 X と要因 A の関係を検討する。

# 考察

ある一つの事例で要因 A のあとに現象 X が増えた。したがって、要因 A は現象 X の主な原因である。
MD
cat > research/questions.md <<'MD'
# 調査の問い(学生が書く)

| id | 小問い(自分の言葉で) | 何が分かれば答えになるか | 状態 |
|---|---|---|---|
| Q1 | 現象 X はいつごろから見られるか | 年ごとの記録 | 着手 |
MD
QUOTE="したがって、要因 A は現象 X の主な原因である"
COMMENT="W1(論理の飛躍): 一つの事例から『主な原因』まで言うには、どんな前提が要りますか？"
else
cat > manuscript/main.md <<'MD'
---
title: "(sample manuscript)"
---

# Introduction

Phenomenon X is often discussed. This paper examines how factor A relates to phenomenon X.

# Discussion

In one case, phenomenon X increased after factor A. Therefore factor A is the main cause of phenomenon X.
MD
cat > research/questions.md <<'MD'
# Research questions (written by the student)

| id | question (your own words) | what would answer it | status |
|---|---|---|---|
| Q1 | Since when has phenomenon X been observed? | yearly records | started |
MD
QUOTE="Therefore factor A is the main cause of phenomenon X"
COMMENT="W1 (leap in reasoning): what premise would let one case support 'the main cause'?"
fi
python3 -B tools/rk/rk.py ledger add-source --doi 10.1038/s41598-023-41032-5 --title "Fabrication and errors in the bibliographic citations generated by ChatGPT" --year 2023 >/dev/null
python3 -B tools/rk/rk.py ledger add-claim --claim "(claim placeholder)" --source-id S001 --locator "p. 3" >/dev/null
python3 -B tools/rk/rk.py annot flag --doc manuscript/main.md --quote "$QUOTE" --code W1 --comment "$COMMENT" --severity 必須 >/dev/null
